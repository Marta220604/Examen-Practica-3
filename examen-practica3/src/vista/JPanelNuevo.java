    private void anadirCoche() {
        jLabelError.setText(""); // borra el error del intento anterior
        try {
            
            String matricula = jTextFieldMatricula.getText().trim();
            float precio = Float.parseFloat(jTextFieldPrecio.getText().trim().replace(',', '.'));
            LocalDate fecha = LocalDate.parse(jTextFieldFechaMatriculacion.getText().trim());

           //  En cuanto una falla se muestra su mensaje y ya no se miran las demas
             if (!ControlErrores.comprobarFecha(fecha)) {
                jLabelError.setText("Fecha incorrecta: La fecha debe estar entre 1990 y la fecha actual!");
            } else if (!ControlErrores.comprobarPrecio(precio)) {
                jLabelError.setText("Precio incorrecto: no puedo costar mas de 150.000 ni ser negativo");
            }else if(!ControlErrores.comprobarFormato(matricula)){
                jLabelError.setText("Matricula incorrecta");
            } else {
                //  guardar y dejar el formulario en blanco para el siguiente
                gestion.añadirCoche(new Coche(matricula, fecha, precio));
                jTextFieldFechaMatriculacion.setText("");
                jTextFieldMatricula.setText("");
                jTextFieldPrecio.setText("");
            }
        } catch (NumberFormatException e) {
            jLabelError.setText("Precio debe ser numéricos");
        } catch (DateTimeParseException e) {
            jLabelError.setText("Fecha incorrecta, usa el formato aaaa-mm-dd");
        }
    }

