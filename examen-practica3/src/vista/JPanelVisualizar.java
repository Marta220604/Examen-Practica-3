    //metodo que muestra los datos de los coches en pantalla
    //si la lista de coches esta vacia no muestra nada y los botones quedan inhabilitados
    public void refrescar() {
        if (gestion.esVacia()) {
            jTextFieldFechaMatriculacion.setText("");
            jTextFieldMatricula.setText("");
            jTextFieldPrecio.setText("");
            setNavegacion(false, false, false, false, false);
        } else {
            mostrarCoche(gestion.obtenerCocheActual());
            setNavegacion(!gestion.esPrimero(), !gestion.esUltimo(), !gestion.esPrimero(), !gestion.esUltimo(), true);
        }
    }
    
    public void mostrarCoche(Coche c) {
        jTextFieldMatricula.setText(String.valueOf(c.getMatricula()));
        jTextFieldPrecio.setText(String.valueOf(c.getPrecio()));
        jTextFieldFechaMatriculacion.setText(String.valueOf(c.getFechamatriculacion()));
    }
    
    
    //metodo que controla que los botones esten activados o desactivados
    public void setNavegacion(boolean anterior, boolean siguiente, boolean primero, boolean ultimo, boolean borrar) {

        jButtonRetroceder.setEnabled(anterior);
        jButtonAvanzar.setEnabled(siguiente);
        jButtonIrPrimero.setEnabled(primero);
        jButtonIrUltimo.setEnabled(ultimo);
        jButtonBorrar.setEnabled(borrar);
    }

